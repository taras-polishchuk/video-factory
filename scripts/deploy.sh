#!/usr/bin/env bash
# deploy.sh — one-click entry point for the Video Factory SaaS
#
# Usage:
#   ./scripts/deploy.sh <domain> [--help] [--dry-run]
#
# Behaviour:
#   1. Verifies all required env vars (HETZNER_TOKEN, CLOUDFLARE_API_TOKEN,
#      STRIPE_SECRET_KEY, STRIPE_WEBHOOK_SECRET, VIDEO_FACTORY_SECRET_KEY,
#      VIDEO_FACTORY_DB_KEY, VIDEO_FACTORY_SESSION_SECRET)
#   2. Writes infra/hosts/<domain>.env with the deploy-time config
#   3. Rewrites Caddyfile with the real domain
#   4. Calls provision-and-deploy.sh (which plans by default; pass
#      --apply to actually create resources)
#   5. Runs the smoke check (curl /health + headers)
#
# Idempotency: a second run with the same <domain> will
#   (a) reuse the existing tofu state (no extra resources),
#   (b) re-rsync + re-up the compose stack (no-op for already-running services),
#   (c) report "deploy: no changes" at the end.
# No tokens are logged.
#
# IMPORTANT: this script NEVER echoes tokens or writes them to git-
# tracked files. Sensitive values live only in the host's env.

set -euo pipefail

print_usage() {
  cat <<USAGE
Usage: $0 <domain> [--dry-run]

Deploys a fresh Video Factory SaaS instance at <domain>.

Required env vars (no defaults; never logged):
  HETZNER_TOKEN                 Hetzner Cloud API token
  CLOUDFLARE_API_TOKEN          Cloudflare DNS-edit token (zone must exist)
  CLOUDFLARE_ZONE_ID            Cloudflare zone id where the DNS record lives
  STRIPE_SECRET_KEY             Stripe secret (test mode for dry-run, live for prod)
  STRIPE_WEBHOOK_SECRET         Stripe webhook signing secret
  VIDEO_FACTORY_SECRET_KEY      Fernet key for the credential vault
  VIDEO_FACTORY_DB_KEY          SQLCipher DB key
  VIDEO_FACTORY_SESSION_SECRET  Session cookie HMAC key

Optional env vars (with defaults):
  HCLOUD_SERVER_TYPE  default "cx22"
  HCLOUD_LOCATION     default "fsn1"
  ADMIN_CIDR          default "0.0.0.0/0" (operator MUST override before apply)

Examples:
  $0 video-factory.example.com             # plan-only by default
  APPLY=1 $0 video-factory.example.com     # plan + apply
  $0 video-factory.example.com --dry-run   # just check required env
USAGE
}

# ─── Parse args ─────────────────────────────────────────────────
DOMAIN=""
DRY_RUN=0

for arg in "$@"; do
  case "$arg" in
    --help|-h) print_usage; exit 0 ;;
    --dry-run) DRY_RUN=1 ;;
    -*) echo "ERROR: unknown argument $arg" >&2; print_usage; exit 2 ;;
    *)
      if [ -z "$DOMAIN" ]; then DOMAIN="$arg"; else
        echo "ERROR: only one domain argument allowed" >&2; exit 2
      fi
      ;;
  esac
done

if [ -z "$DOMAIN" ]; then
  print_usage; exit 2
fi

# ─── Validate required env (fail fast on missing tokens) ───────
required_vars=(
  HETZNER_TOKEN
  CLOUDFLARE_API_TOKEN
  CLOUDFLARE_ZONE_ID
  STRIPE_SECRET_KEY
  STRIPE_WEBHOOK_SECRET
  VIDEO_FACTORY_SECRET_KEY
  VIDEO_FACTORY_DB_KEY
  VIDEO_FACTORY_SESSION_SECRET
)
missing=()
for v in "${required_vars[@]}"; do
  if [ -z "${!v:-}" ]; then missing+=("$v"); fi
done
if [ "${#missing[@]}" -gt 0 ]; then
  echo "ERROR: missing required env vars:" >&2
  for v in "${missing[@]}"; do echo "  $v" >&2; done
  exit 1
fi

# ─── Discover repo root and host env path ─────────────────────
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HOSTS_DIR="$ROOT/infra/hosts"
HOST_ENV="$HOSTS_DIR/$DOMAIN.env"
mkdir -p "$HOSTS_DIR"

# Write the host env. The shell redirects write the values, but the
# file ends up chmod 0600 and lives OUTSIDE of git (infra/hosts/ is
# .gitignore'd). Tokens never enter any other file.
cat > "$HOST_ENV" <<EOF
# Generated by deploy.sh on $(date -u +%FT%TZ). Do NOT edit by hand.
# Values here are derived from the operator's environment and never
# include plaintext tokens. Sensitive values come from systemd
# LoadCredential= on the target host (see systemd/secret-distribution.md).
DOMAIN=$DOMAIN
HCLOUD_SERVER_TYPE=${HCLOUD_SERVER_TYPE:-cx22}
HCLOUD_LOCATION=${HCLOUD_LOCATION:-fsn1}
ADMIN_CIDR=${ADMIN_CIDR:-0.0.0.0/0}
VIDEO_FACTORY_SERVER_IP=${VIDEO_FACTORY_SERVER_IP:-}
EOF
chmod 0600 "$HOST_ENV"

# ─── Rewrite Caddyfile with the real domain ────────────────────
CADDYFILE="$ROOT/Caddyfile"
if [ ! -f "$CADDYFILE" ]; then
  echo "ERROR: $CADDYFILE missing" >&2; exit 1
fi
# Replace the placeholder domain with the real one. Idempotent.
sed -i.bak "s|video-factory\.example\.com|$DOMAIN|g" "$CADDYFILE"
rm -f "$CADDYFILE.bak"

# ─── Provision + deploy ────────────────────────────────────────
# Default: plan only (no resource creation). Operator must opt-in by
# passing APPLY=1 in the environment.
if [ "${APPLY:-0}" -eq 1 ] && [ "$DRY_RUN" -eq 0 ]; then
  PROVISION_FLAG="--apply"
else
  PROVISION_FLAG=""
fi

"$ROOT/scripts/provision-and-deploy.sh" "$DOMAIN" $PROVISION_FLAG

# ─── Smoke check (only meaningful after a real apply) ──────────
if [ "${APPLY:-0}" -eq 1 ] && [ "$DRY_RUN" -eq 0 ]; then
  echo "smoke: GET https://$DOMAIN/health"
  for i in $(seq 1 30); do
    sleep 1
    if curl -fsS -m 3 "https://$DOMAIN/health" >/dev/null 2>&1; then
      echo "smoke: 200 OK"
      break
    fi
  done

  echo "smoke: GET https://$DOMAIN/ (verify security headers)"
  curl -sSI -m 5 "https://$DOMAIN/" 2>/dev/null | head -20
fi

echo "deploy: $DOMAIN — complete"