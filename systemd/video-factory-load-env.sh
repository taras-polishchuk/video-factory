#!/usr/bin/env bash
# /usr/local/bin/video-factory-load-env.sh — materialise credentials into .env.production
#
# Called from video-factory.service ExecStartPre=. systemd populates
# $CREDENTIALS_DIRECTORY with the files listed in LoadCredential=. We
# copy the values into /opt/video-factory/.env.production so docker
# compose can read them.
#
# The .env.production file is mode 0600 (written below) and is NOT in
# git (infra/hosts/ + .env.production are both .gitignore'd).

set -euo pipefail

ENV_FILE="${1:-/opt/video-factory/.env.production}"
CRED_DIR="${CREDENTIALS_DIRECTORY:-/etc/video-factory/credentials}"

mkdir -p "$(dirname "$ENV_FILE")"

# Start with a clean file (rotate-friendly).
> "$ENV_FILE"
chmod 0600 "$ENV_FILE"

{
  echo "# Generated by video-factory-load-env.sh on $(date -u +%FT%TZ)"
  echo "# DO NOT edit by hand. DO NOT commit. Contents come from systemd"
  echo "# LoadCredential= entries in video-factory.service."
  echo ""
  for name in \
      cloudflare_api_token \
      hetzner_token \
      stripe_secret_key \
      stripe_webhook_secret \
      video_factory_secret_key \
      video_factory_db_key \
      video_factory_session_secret
  do
    cred="$CRED_DIR/$name"
    if [ ! -f "$cred" ]; then
      echo "FATAL: credential $cred missing" >&2
      exit 1
    fi
    # Validate non-empty.
    if [ ! -s "$cred" ]; then
      echo "FATAL: credential $cred is empty" >&2
      exit 1
    fi
    upper="$(echo "$name" | tr '[:lower:]' '[:upper:]')"
    # Use single quotes to escape any character; replace any embedded
    # single quotes with the SQL/JS escape.
    val="$(cat "$cred" | sed -e "s/'/'\\\\''/g")"
    echo "$upper='$val'" >> "$ENV_FILE"
  done
} >> "$ENV_FILE"